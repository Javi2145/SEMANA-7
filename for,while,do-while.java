public class TiposDeCiclos { 

    public static void main(String[] args) { 

        // FOR 

        System.out.println("Ciclo FOR:"); 

        for (int i = 1; i <= 10; i++) { 

            System.out.print(i + " "); 

        } 

        // WHILE 

        System.out.println("\n\nCiclo WHILE:"); 

        int j = 1; 

        while (j <= 10) { 

            System.out.print(j + " "); 

            j++; 

        } 

        // DO-WHILE 

        System.out.println("\n\nCiclo DO-WHILE:"); 

        int k = 1; 

        do { 

            System.out.print(k + " "); 

            k++; 

        } while (k <= 10); 

        System.out.println(); 

    } 

} 