public class SeriesNumericas { 

    public static void main(String[] args) { 

        // Pares 

        System.out.print("Pares: "); 

        for (int i = 2; i <= 20; i += 2) { 

            System.out.print(i + " "); 

        } 

        // Cuadrados 

        System.out.print("\nCuadrados: "); 

        for (int i = 1; i <= 10; i++) { 

            int termino = i * i; 

            System.out.print(termino + " "); 

        } 

        System.out.println(); 

    } 

} 