public class CiclosAnidados { 

    public static void main(String[] args) { 

        for (int fila = 1; fila <= 3; fila++) { 

            for (int col = 1; col <= 4; col++) { 

                System.out.print("* "); 

            } 

            System.out.println(); 

        } 

    } 

} 